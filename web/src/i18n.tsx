export type Translate = (key: keyof typeof en, vars?: Record<string, string | number>) => string;

interface I18nContextValue {
	t: Translate;
}

const I18nContext = createContext<I18nContextValue | null>(null);

/** Looks up a UI string and interpolates `{var}` placeholders. */
export const t: Translate = (key, vars) => {
	let str: string = en[key];
	if (vars) {
		for (const [k, v] of Object.entries(vars)) {
			str = str.replaceAll(`{${k}}`, String(v));
		}
	}
	return str;
};

export function LanguageProvider({ children }: { children: ReactNode }) {
	const value = useMemo(() => ({ t }), []);
	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
	const ctx = useContext(I18nContext);
	if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
	return ctx;
}

/** Convenience: translation function only. */
export function useT(): Translate {
	return useI18n().t;
}
